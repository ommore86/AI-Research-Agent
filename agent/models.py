"""
Pydantic data models for the AI Research Agent.
Guarantees strict schema validation for plans, tool calls, and final outputs.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ConfidenceLevel(str, Enum):
    """Subjective and empirical confidence assessment."""
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"


class ToolCall(BaseModel):
    """Specification of a tool to be invoked by the orchestrator."""
    tool_name: str = Field(..., description="Unique name of the tool to execute")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Arguments to pass to the tool")
    rationale: str = Field("", description="Why this tool and query were chosen")


class ToolResult(BaseModel):
    """Outcome of a tool execution with status and metadata."""
    tool_name: str
    arguments: Dict[str, Any]
    success: bool
    output: Any
    error_message: Optional[str] = None
    execution_time_seconds: float = 0.0
    cached: bool = False


class PlanStep(BaseModel):
    """Individual atomic step within an overall research plan."""
    step_number: int = Field(..., description="Sequential index of the step (1-indexed)")
    goal: str = Field(..., description="Objective of this specific research step")
    tool_to_use: str = Field(..., description="Tool name assigned to this step")
    tool_query: str = Field(..., description="Query or input to provide to the tool")
    expected_output: str = Field(..., description="What information this step seeks to extract")


class ResearchPlan(BaseModel):
    """Structured plan generated by the planning step before execution."""
    user_question: str
    intent_summary: str = Field(..., description="Summary of core user intent and domain")
    sub_questions: List[str] = Field(default_factory=list, description="Decomposed research sub-questions")
    steps: List[PlanStep] = Field(default_factory=list, description="Ordered execution steps")
    hypotheses_or_assumptions: List[str] = Field(default_factory=list, description="Initial baseline expectations")


class SourceReference(BaseModel):
    """Standardized representation of an information source."""
    source_id: str = Field(..., description="Identifier e.g. [S1], [S2]")
    title: str = Field(..., description="Title of the source or document")
    url: str = Field(..., description="Direct URL or URI")
    snippet: str = Field(..., description="Key excerpt or summary extracted from source")
    relevance_score: float = Field(default=1.0, ge=0.0, le=1.0, description="Estimated relevance score 0-1")


class KeyFinding(BaseModel):
    """Structured finding with explicit source grounding citations."""
    topic: str = Field(..., description="Sub-topic or dimension")
    insight: str = Field(..., description="Detailed factual finding synthesized from sources")
    citation_ids: List[str] = Field(default_factory=list, description="List of source_ids supporting this claim, e.g. ['S1', 'S2']")


class ExecutionTraceStep(BaseModel):
    """Single recorded step in the agent's execution timeline."""
    stage: str = Field(..., description="e.g. Planning, ToolExecution, Filtering, Synthesis, Critique")
    description: str
    status: str = "completed"
    details: Optional[Dict[str, Any]] = None
    duration_seconds: float = 0.0


class ExecutionTrace(BaseModel):
    """Complete diagnostic log of the agent's run for observability."""
    steps: List[ExecutionTraceStep] = Field(default_factory=list)
    total_duration_seconds: float = 0.0
    tools_called: int = 0
    tools_succeeded: int = 0
    tools_failed: int = 0
    sources_retrieved: int = 0
    sources_filtered_out: int = 0
    tokens_estimated: int = 0


class ResearchReport(BaseModel):
    """
    Final synthesized research answer.
    Strictly conforms to the assignment specification.
    """
    user_question: str = Field(..., description="Original research question submitted by user")
    short_answer: str = Field(..., description="Concise executive summary answering the question in 2-4 sentences")
    key_findings: List[str] = Field(..., description="Bullet points of major discoveries and insights")
    structured_findings: Optional[List[KeyFinding]] = Field(default=None, description="Optional cited findings breakdown")
    sources_used: List[SourceReference] = Field(..., description="List of verified sources consulted during research")
    confidence_level: ConfidenceLevel = Field(..., description="Confidence assessment: High, Medium, or Low")
    confidence_rationale: str = Field(..., description="Engineering explanation for confidence rating")
    limitations_or_assumptions: List[str] = Field(..., description="Data gaps, temporal boundaries, or assumptions made")
    suggested_next_steps: List[str] = Field(..., description="Actionable recommendations for deeper follow-up research")
    trace: Optional[ExecutionTrace] = Field(default=None, description="Observability trace of agent execution")


class EvaluationMetricScore(BaseModel):
    """Individual metric evaluation score."""
    metric_name: str
    score: float = Field(..., ge=0.0, le=1.0)
    passed: bool
    rationale: str


class EvaluationResult(BaseModel):
    """Result of evaluating the agent on a single benchmark query."""
    query_id: str
    user_question: str
    category: str
    report: Optional[ResearchReport] = None
    execution_time_seconds: float = 0.0
    metrics: List[EvaluationMetricScore] = Field(default_factory=list)
    overall_passed: bool = True
    observations: str = ""
